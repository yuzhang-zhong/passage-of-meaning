function sleep(ms) {
  return new Promise((resolvePromise) => setTimeout(resolvePromise, ms));
}

function normalize(text) {
  return String(text ?? '').replace(/\s+/g, ' ').trim();
}

function ngrams(text, word) {
  const clean = normalize(text).replace(/[^\u3400-\u9fffA-Za-z0-9]+/g, '').toLowerCase();
  const grams = new Map();
  for (const [size, weight] of [[1, .25], [2, 1], [3, 1.6]]) {
    for (let index = 0; index <= clean.length - size; index += 1) {
      const gram = clean.slice(index, index + size);
      if (gram === word || (size === 1 && word.includes(gram))) continue;
      grams.set(gram, (grams.get(gram) ?? 0) + weight);
    }
  }
  return grams;
}

function containment(left, right) {
  const leftTotal = [...left.values()].reduce((sum, value) => sum + value, 0);
  const rightTotal = [...right.values()].reduce((sum, value) => sum + value, 0);
  const denominator = Math.min(leftTotal, rightTotal);
  if (!denominator) return 0;
  let common = 0;
  for (const [key, leftValue] of left) {
    common += Math.min(leftValue, right.get(key) ?? 0);
  }
  return common / denominator;
}

function queryHints(query) {
  const group = query.match(/\(([^)]+)\)/)?.[1];
  return group ? group.split('|').filter(Boolean) : [];
}

function excerptCandidates(text, word) {
  const normalized = normalize(text);
  const sentences = normalized.split(/(?<=[。！？!?；;])/).map((item) => item.trim()).filter(Boolean);
  const matches = sentences.filter((sentence) => sentence.includes(word));
  if (matches.length) return matches;
  const index = normalized.indexOf(word);
  if (index < 0) return [];
  return [normalized.slice(Math.max(0, index - 70), Math.min(normalized.length, index + word.length + 90))];
}

function clipExcerpt(text, word) {
  const normalized = normalize(text);
  if (normalized.length <= 150) return normalized;
  const index = normalized.indexOf(word);
  if (index < 0) return `${normalized.slice(0, 149)}…`;
  const start = Math.max(0, index - 55);
  const end = Math.min(normalized.length, index + word.length + 85);
  return `${start > 0 ? '…' : ''}${normalized.slice(start, end)}${end < normalized.length ? '…' : ''}`;
}

function yearFromPath(path) {
  const matches = String(path ?? '').match(/(?:18|19|20)\d{2}/g);
  return matches ? Number(matches.at(-1)) : null;
}

function sourceLabel(path) {
  return basename(String(path ?? ''), '.txt').replace(/^\d{4}\s+/, '').replace(/_/g, ' · ');
}

function rankResults(target, query, results) {
  const targetVector = ngrams(`${target.sense.name} ${target.sense.shortName} ${target.sense.description}`, target.word);
  const hints = queryHints(query);
  const ranked = [];
  for (const result of results ?? []) {
    const year = yearFromPath(result.path);
    if (!year || sensitiveFragments.some((fragment) => result.origin_text?.includes(fragment))) continue;
    for (const sentence of excerptCandidates(result.origin_text, target.word)) {
      if (sentence.length < 8) continue;
      const excerpt = clipExcerpt(sentence, target.word);
      const hintHits = hints.filter((hint) => excerpt.includes(hint)).length;
      const semantic = containment(targetVector, ngrams(excerpt, target.word));
      const cleanSource = /文学|报刊|应用文|学术|教材|科普/.test(result.path ?? '') ? .025 : 0;
      const score = semantic + hintHits * .08 + cleanSource;
      ranked.push({
        score: Number(score.toFixed(4)),
        excerpt,
        year,
        path: result.path,
        recordId: result.record_id,
        source: sourceLabel(result.path),
        hintHits,
      });
    }
  }
  return ranked.sort((left, right) => right.score - left.score || left.excerpt.length - right.excerpt.length).slice(0, 3);
}

async function search(query) {
  const response = await fetch('https://corpus.pku.edu.cn/api/ccl_simple/query', {
    method: 'POST',
    headers: { 'Content-Type': 'application/json' },
    body: JSON.stringify({ query, page: 1, corpus: 'tongyongyuliao', highlight: false }),
  });
  if (!response.ok) throw new Error(`CCL ${response.status}: ${await response.text()}`);
  return response.json();
}

